function Get-CommandVersionSafe {
    param([string]$CommandName, [string[]]$Arguments)
    try {
        $output = & $CommandName @Arguments 2>&1 | Select-Object -First 1
        if ([string]::IsNullOrWhiteSpace(($output | Out-String))) {
            return "unknown"
        }
        return ($output | Out-String).Trim()
    }
    catch {
        return "unknown"
    }
}

function Copy-DirectoryMerge {
    param(
        [string]$From,
        [string]$To,
        [string]$Label,
        [System.Collections.Generic.List[string]]$Warnings,
        [string[]]$ExcludeDirectoryNames = @()
    )

    if (-not (Test-Path $From)) {
        $Warnings.Add("$Label source not found: $From")
        return $false
    }

    if (-not (Test-Path $To)) {
        New-Item -ItemType Directory -Path $To -Force | Out-Null
    }

    Get-ChildItem -Path $From -Force | ForEach-Object {
        if ($_.PSIsContainer -and ($ExcludeDirectoryNames -contains $_.Name)) {
            return
        }

        $destination = Join-Path $To $_.Name
        Copy-Item -Path $_.FullName -Destination $destination -Recurse -Force
    }

    Write-Ok "$Label copied/merged"
    return $true
}

function Copy-FileIfExists {
    param(
        [string]$From,
        [string]$To,
        [string]$Label,
        [System.Collections.Generic.List[string]]$Warnings
    )

    if (-not (Test-Path $From)) {
        $Warnings.Add("$Label source file not found: $From")
        return $false
    }

    $destinationDirectory = Split-Path -Path $To -Parent
    if (-not (Test-Path $destinationDirectory)) {
        New-Item -ItemType Directory -Path $destinationDirectory -Force | Out-Null
    }

    Copy-Item -Path $From -Destination $To -Force
    Write-Ok "$Label copied"
    return $true
}

function Read-YamlStringList {
    # Lee una lista YAML de strings bajo una clave dada.
    # Soporta clave de nivel superior (ej. 'commands:') o anidada un
    # nivel (ej. 'overrides:' -> 'agents:'). Parser minimo suficiente
    # para los manifiestos GRM (listas planas de strings). Ver
    # GRM-SCK_Plan_Adaptacion_Instalador_v1 (Opcion A).
    param(
        [string]$Path,
        [string]$TopKey,
        [string]$NestedKey = $null
    )

    if (-not (Test-Path $Path)) { return @() }
    $lines = Get-Content -Path $Path
    $result = [System.Collections.Generic.List[string]]::new()

    $inTop = $false
    $inNested = $false
    $topIndent = -1

    foreach ($raw in $lines) {
        $line = $raw -replace '\t', '    '
        if ($line -match '^\s*#') { continue }
        if ([string]::IsNullOrWhiteSpace($line)) { continue }

        $indent = ($line -replace '^(\s*).*$', '$1').Length
        $trimmed = $line.Trim()

        if (-not $inTop) {
            if ($trimmed -match "^${TopKey}:") {
                $inTop = $true
                $topIndent = $indent
                if (-not $NestedKey) { $inNested = $true }
            }
            continue
        }

        if ($indent -le $topIndent -and $trimmed -notmatch '^-') {
            break
        }

        if ($NestedKey -and -not $inNested) {
            if ($trimmed -match "^${NestedKey}:") { $inNested = $true }
            continue
        }

        if ($trimmed -match '^-\s*(.+)$') {
            $item = $Matches[1].Trim()
            $item = ($item -replace '\s+#.*$', '').Trim()
            $item = $item.Trim('"').Trim("'")
            if ($item) { $result.Add($item) }
        }
    }

    return $result.ToArray()
}

function Copy-ManifestFile {
    # Copia un unico fichero declarado en el manifiesto. Si el origen
    # no existe, la instalacion FALLA (no se degrada). Cumple CA-04.
    param(
        [string]$From,
        [string]$To,
        [string]$Label,
        [System.Collections.Generic.List[string]]$Deployed
    )

    if (-not (Test-Path $From)) {
        throw "Declared artifact not found in Source of Truth: $From ($Label)"
    }

    $destinationDirectory = Split-Path -Path $To -Parent
    if (-not (Test-Path $destinationDirectory)) {
        New-Item -ItemType Directory -Path $destinationDirectory -Force | Out-Null
    }

    Copy-Item -Path $From -Destination $To -Force
    if ($null -ne $Deployed) { $Deployed.Add("$Label|$From|$To") | Out-Null }
    Write-Ok "Deployed $Label"
    return $true
}

function Install-CorporateAgentsAndPrompts {
    # Despliega agentes y prompts corporativos por manifiesto, fichero
    # a fichero. Sustituye la copia por directorio completo (H-INST-01,
    # H-INST-02). Cumple PC-01 y PC-02.
    param(
        [string]$SourceRepoPath,
        [string]$TargetPath,
        [System.Collections.Generic.List[string]]$Deployed
    )

    $extYml = Join-Path $SourceRepoPath "extensions/grm-corporate-workflow/extension.yml"
    $preYml = Join-Path $SourceRepoPath "presets/grm-corporate-governance/preset.yml"

    # 1. Comandos corporativos: agent + prompt por cada corp.<cmd>
    $commands = Read-YamlStringList -Path $extYml -TopKey "commands"
    foreach ($cmd in $commands) {
        $agentFrom = Join-Path $SourceRepoPath "extensions/grm-corporate-workflow/agents/$cmd.agent.md"
        $agentTo = Join-Path $TargetPath ".github/agents/$cmd.agent.md"
        Copy-ManifestFile -From $agentFrom -To $agentTo -Label "corp agent: $cmd" -Deployed $Deployed | Out-Null

        $promptFrom = Join-Path $SourceRepoPath "extensions/grm-corporate-workflow/prompts/$cmd.prompt.md"
        $promptTo = Join-Path $TargetPath ".github/prompts/$cmd.prompt.md"
        Copy-ManifestFile -From $promptFrom -To $promptTo -Label "corp prompt: $cmd" -Deployed $Deployed | Out-Null
    }

    # 2. Overrides de preset: solo agentes (el preset no declara prompts)
    $overrides = Read-YamlStringList -Path $preYml -TopKey "overrides" -NestedKey "agents"
    foreach ($agent in $overrides) {
        $ovrFrom = Join-Path $SourceRepoPath "presets/grm-corporate-governance/agents/$agent"
        $ovrTo = Join-Path $TargetPath ".github/agents/$agent"
        Copy-ManifestFile -From $ovrFrom -To $ovrTo -Label "preset override agent: $agent" -Deployed $Deployed | Out-Null
    }
}

function Read-SkillFrontmatter {
    # Extrae el bloque de frontmatter de un SKILL.md: desde la primera
    # linea, que debe ser exactamente '---', hasta la siguiente linea
    # que sea tambien exactamente '---'. Sin cierre, no hay frontmatter
    # que leer (D-P20-02): el llamador lo trata como fallo de forma.
    #
    # Dentro del bloque, pares clave: valor planos, un nivel, sin
    # anidar. No reutiliza Read-YamlScalar: un frontmatter no tiene
    # TopKey/NestedKey, name y description estan al mismo nivel, y
    # Read-YamlScalar lee el fichero completo sin acotar donde termina
    # el YAML, lo que arriesga capturar texto del cuerpo Markdown.
    #
    # No soporta valores plegados en varias lineas (estilo '>' o '|').
    # El corpus actual no los usa; si aparecen, esta funcion los trata
    # como valor vacio y Assert-SkillShape lo reporta como campo
    # ausente, nunca como exito silencioso.
    param(
        [string]$Path
    )

    $result = @{}
    if (-not (Test-Path $Path)) { return $result }

    $lines = @(Get-Content -Path $Path)
    if ($lines.Count -eq 0 -or $lines[0].Trim() -ne '---') {
        return $result
    }

    $closeIndex = -1
    for ($i = 1; $i -lt $lines.Count; $i++) {
        if ($lines[$i].Trim() -eq '---') {
            $closeIndex = $i
            break
        }
    }
    if ($closeIndex -lt 0) {
        return $result
    }

    for ($i = 1; $i -lt $closeIndex; $i++) {
        $line = $lines[$i]
        if ($line -match '^\s*#') { continue }
        if ([string]::IsNullOrWhiteSpace($line)) { continue }
        if ($line -match '^([A-Za-z0-9_]+):\s*(.*)$') {
            $key = $Matches[1]
            $val = $Matches[2].Trim()
            $val = $val.Trim('"').Trim("'")
            $result[$key] = $val
        }
    }

    return $result
}

function Assert-SkillShape {
    # P3 (D-P19-02, D-P20-01b, D-P20-03b, D-P20-04): valida la forma de
    # toda skill desplegable en la Source of Truth, declarada o no en
    # el manifiesto.
    #
    # Se ejecuta sobre el subarbol de origen, antes de copiar nada,
    # igual que la puerta de existencia de Install-CorporateSkills.
    # Ambas puertas conviven: la de existencia cubre las skills
    # declaradas en extension.yml; esta cubre todo directorio de primer
    # nivel que tenga SKILL.md, declarado o no, porque el subarbol
    # completo se despliega igual (D-P19-10).
    #
    # _shared queda fuera sin excepcion explicita: no tiene SKILL.md
    # (D-P19-01), asi que nunca entra en el bucle.
    #
    # Un directorio sin SKILL.md no es un incumplimiento aqui: nadie
    # prometio que fuera una skill. Es criterio de inclusion, no una
    # regla que pueda fallar.
    #
    # Todos los incumplimientos se acumulan y se lanzan juntos, para no
    # obligar a corregir y reinstalar seis veces (mismo patron que la
    # puerta de existencia).
    param(
        [string]$SkillsFrom
    )

    $nameSyntax = '^[a-z0-9]+(-[a-z0-9]+)*$'
    $problems = [System.Collections.Generic.List[string]]::new()

    $skillDirs = @(Get-ChildItem -LiteralPath $SkillsFrom -Directory -Force)
    $validatedDirs = [System.Collections.Generic.List[string]]::new()
    foreach ($dir in $skillDirs) {
        $skillMd = Join-Path $dir.FullName "SKILL.md"
        if (-not (Test-Path $skillMd)) {
            continue
        }
        $validatedDirs.Add($dir.Name) | Out-Null

        $front = Read-SkillFrontmatter -Path $skillMd
        if ($front.Count -eq 0) {
            $problems.Add("$($dir.Name): frontmatter not parseable (missing or unclosed '---' block)") | Out-Null
            continue
        }

        $name = $front['name']
        $description = $front['description']

        if ([string]::IsNullOrWhiteSpace($name)) {
            $problems.Add("$($dir.Name): missing 'name' in frontmatter") | Out-Null
        }
        if ([string]::IsNullOrWhiteSpace($description)) {
            $problems.Add("$($dir.Name): missing 'description' in frontmatter") | Out-Null
        }
        if (-not [string]::IsNullOrWhiteSpace($name)) {
            if ($name -cne $dir.Name) {
                $problems.Add("$($dir.Name): 'name' ('$name') does not match directory name") | Out-Null
            }
            if ($name -cnotmatch $nameSyntax -or $name.Length -gt 64) {
                $problems.Add("$($dir.Name): 'name' ('$name') must be lowercase-with-hyphens, up to 64 characters") | Out-Null
            }
        }
        if (-not [string]::IsNullOrWhiteSpace($description) -and $description.Length -gt 1024) {
            $problems.Add("$($dir.Name): 'description' exceeds 1024 characters ($($description.Length))") | Out-Null
        }
    }

    if ($problems.Count -gt 0) {
        throw "Skill shape validation failed: $($problems -join '; ')"
    }

    # P5b (D-P21-08): en exito, devuelve los directorios de primer nivel
    # que llegaron a tener SKILL.md y pasaron las seis reglas -no todos
    # los de $skillDirs, que incluye tambien _shared-. Esta funcion es
    # la unica que sabe si un directorio tenia forma de skill; el
    # informe no vuelve a preguntarselo a nadie mas.
    return $validatedDirs
}

function Install-CorporateSkills {
    # Despliega el subarbol de skills corporativas en el runtime, que es
    # donde el agente las descubre. Copy-DirectoryMerge ya lleva la
    # extension entera a extensions/, pero .github/skills/ quedaba vacio.
    #
    # El manifiesto es puerta, no inventario (D-P19-10, D-P19-11): toda
    # skill declarada debe existir con su SKILL.md ANTES de copiar nada,
    # y lo que se copia es el subarbol completo, incluidas las carpetas
    # que no se declaran.
    #
    # Segunda puerta, tambien previa a copiar (P3): Assert-SkillShape
    # valida la forma de todo directorio con SKILL.md, declarado o no.
    # Existencia y forma son preguntas distintas y se comprueban por
    # separado; ver Assert-SkillShape para el detalle de las reglas.
    #
    # skills/_shared es una de ellas (D-P19-01). No es una skill, no se
    # declara y no lleva SKILL.md, pero los dos SKILL.md invocan sus
    # scripts por ruta del runtime. Sin el, el primer corp.erase falla.
    #
    # Sin purga (D-P19-12): copia y sobrescribe, nunca borra. Es
    # deliberadamente menos agresiva que resources/tools/Sync-GrmSkills.ps1,
    # que espeja con robocopy /MIR sobre un runtime desechable. Aqui el
    # destino puede contener skills anadidas por el proyecto consumidor,
    # y la politica del instalador es no destruir .github.
    #
    # Una entrada por fichero en $Deployed (D-P19-09), de modo que
    # Assert-DeployedProvenance compara la huella SHA-256 de origen y
    # destino. La verificacion no es nueva: es la que ya cubre agentes y
    # prompts.
    param(
        [string]$SourceRepoPath,
        [string]$TargetPath,
        [System.Collections.Generic.List[string]]$Deployed
    )

    $extYml     = Join-Path $SourceRepoPath "extensions/grm-corporate-workflow/extension.yml"
    $skillsFrom = Join-Path $SourceRepoPath "extensions/grm-corporate-workflow/skills"

    if (-not (Test-Path $skillsFrom)) {
        throw "Skills subtree not found in Source of Truth: $skillsFrom"
    }

    # 1. Puerta previa sobre el conjunto completo. Falla antes de copiar,
    #    para no dejar el runtime a medio desplegar.
    $skills = @(Read-YamlStringList -Path $extYml -TopKey "skills")
    $missingSkills = [System.Collections.Generic.List[string]]::new()
    foreach ($skill in $skills) {
        $skillDir = Join-Path $skillsFrom $skill
        if (-not (Test-Path $skillDir)) {
            $missingSkills.Add($skill) | Out-Null
            continue
        }
        if (-not (Test-Path (Join-Path $skillDir "SKILL.md"))) {
            $missingSkills.Add("$skill (missing SKILL.md)") | Out-Null
        }
    }
    if ($missingSkills.Count -gt 0) {
        throw "Declared skills not found or incomplete in Source of Truth: $($missingSkills -join ', '). Nothing was copied."
    }

    # 1b. Validacion de forma (P3, D-P20-01b): todo directorio de primer
    #     nivel de la Source of Truth que tenga SKILL.md, declarado o no.
    #     Ver Assert-SkillShape. Tambien corta antes de copiar nada.
    Assert-SkillShape -SkillsFrom $skillsFrom

    # 2. Despliegue del subarbol completo, fichero a fichero.
    #    El prefijo y los ficheros tienen que venir del mismo proveedor.
    #    Resolve-Path conserva la forma corta 8.3 que se le pasa, mientras
    #    que FullName de Get-ChildItem devuelve la forma larga expandida.
    #    Restar longitudes entre las dos formas descuadra la ruta relativa:
    #    medido, C:\Users\SESANC~1\... son 51 caracteres y
    #    C:\Users\sesanchez\... son 52 para el mismo directorio.
    #    La comprobacion de prefijo convierte esa clase de error en un fallo
    #    duro en lugar de en una ruta silenciosamente mal formada.
    $skillsRoot = (Get-Item -LiteralPath $skillsFrom).FullName.TrimEnd('\')
    $prefix     = $skillsRoot + '\'
    $files      = @(Get-ChildItem -LiteralPath $skillsRoot -Recurse -File -Force)
    foreach ($file in $files) {
        if (-not $file.FullName.StartsWith($prefix, [System.StringComparison]::OrdinalIgnoreCase)) {
            throw "File outside the skills subtree: $($file.FullName) (expected prefix: $prefix)"
        }
        $relative = $file.FullName.Substring($prefix.Length)
        $skillTo  = Join-Path $TargetPath (".github/skills/" + $relative)
        Copy-ManifestFile -From $file.FullName -To $skillTo -Label "corp skill file: $relative" -Deployed $Deployed | Out-Null
    }

    Write-Ok "Corporate skills deployed: $($skills.Count) declared skill(s), $($files.Count) file(s)"
}

function Get-NativePreservedFiles {
    # Resuelve las rutas de fichero (agent + prompt) para cada clave
    # declarada en native_preserved. Opcion A: agent + prompt.
    param(
        [string]$SourceRepoPath,
        [string]$TargetPath
    )
    $preYml = Join-Path $SourceRepoPath "presets/grm-corporate-governance/preset.yml"
    $keys = Read-YamlStringList -Path $preYml -TopKey "native_preserved"
    $files = [System.Collections.Generic.List[string]]::new()
