<#
.SYNOPSIS
Bootstrap or update a GRM Custom Spec Kit workspace.

.DESCRIPTION
Creates or updates a validation workspace for GRM Custom Spec Kit.

Supported modes:
- FailIfExists: safe default. Fails when target directory already exists.
- CleanInstall: creates a clean workspace. If target exists, requires -Force and deletes it.
- UpdateExisting: updates an existing workspace non-destructively. Does not run specify init by default.

Deterministic Spec Kit initialization for CleanInstall:
- specify init --here --integration copilot --script ps --force

Runtime merge policy:
- Does NOT delete .github or .specify generated by Spec Kit, except during an explicit CleanInstall -Force.
- Copies GRM source-of-truth assets into the target.
- Merges runtime files over the clean or existing runtime where names match.
- Preserves additional standard Spec Kit runtime files introduced by the installed version.
- Installs corporate workflows from presets/grm-corporate-governance/workflows into .specify/workflows.
- Merges workflow-registry.json additively, preserving native entries such as speckit.
- Generates installation-report.md in both successful and failed executions.

.EXAMPLES
.\bootstrap-grm-e2e.ps1 -TargetName e2e-demo-01
.\bootstrap-grm-e2e.ps1 -TargetName e2e-demo-01 -InstallMode CleanInstall -Force
.\bootstrap-grm-e2e.ps1 -TargetName e2e-demo-01 -InstallMode UpdateExisting
.\bootstrap-grm-e2e.ps1 -TargetName e2e-demo-01 -Branch main -KeepSourceCache
