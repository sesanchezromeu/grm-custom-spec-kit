function Resolve-TargetWorkspacePolicy {
    param(
        [string]$TargetPath,
        [string]$InstallMode,
        [switch]$Force
    )

    $targetExists = Test-Path $TargetPath

    if ($targetExists -and $InstallMode -eq "FailIfExists") {
        throw "Target directory already exists: $TargetPath. Use -InstallMode CleanInstall -Force to recreate it, or -InstallMode UpdateExisting to update it safely."
    }

    if ($targetExists -and $InstallMode -eq "CleanInstall" -and -not $Force) {
        throw "CleanInstall requires -Force when target directory already exists: $TargetPath"
    }

    if ($targetExists -and $InstallMode -eq "CleanInstall" -and $Force) {
        Remove-Item -Path $TargetPath -Recurse -Force
        New-Item -ItemType Directory -Path $TargetPath -Force | Out-Null
        return "CleanInstall"
    }

    if ($targetExists -and $InstallMode -eq "UpdateExisting") {
        Assert-SpecKitInstallation -TargetPath $TargetPath
        return "UpdateExisting"
    }

    if (-not $targetExists) {
        New-Item -ItemType Directory -Path $TargetPath -Force | Out-Null
        return "CleanInstall"
    }

    throw "Unsupported target workspace state for path: $TargetPath"
}

function ConvertTo-HashtableRecursive {
    param([object]$InputObject)

    if ($null -eq $InputObject) {
        return $null
    }

    if ($InputObject -is [System.Management.Automation.PSCustomObject]) {
        $hash = [ordered]@{}
        foreach ($property in $InputObject.PSObject.Properties) {
            $hash[$property.Name] = ConvertTo-HashtableRecursive -InputObject $property.Value
        }
        return $hash
    }

    if ($InputObject -is [System.Collections.IEnumerable] -and -not ($InputObject -is [string])) {
        $array = @()
        foreach ($item in $InputObject) {
            $array += ConvertTo-HashtableRecursive -InputObject $item
        }
        return $array
    }

    return $InputObject
}

function Test-JsonContainsToken {
    param(
        [object]$InputObject,
        [string]$Token
    )

    if ($null -eq $InputObject) {
        return $false
    }

    if ($InputObject -is [System.Management.Automation.PSCustomObject]) {
        foreach ($property in $InputObject.PSObject.Properties) {
            if ($property.Name -eq $Token) {
                return $true
            }
            if (Test-JsonContainsToken -InputObject $property.Value -Token $Token) {
                return $true
            }
        }
        return $false
    }

    if ($InputObject -is [System.Collections.IDictionary]) {
        foreach ($key in $InputObject.Keys) {
            if ([string]$key -eq $Token) {
                return $true
            }
            if (Test-JsonContainsToken -InputObject $InputObject[$key] -Token $Token) {
                return $true
            }
        }
        return $false
    }

    if ($InputObject -is [System.Collections.IEnumerable] -and -not ($InputObject -is [string])) {
        foreach ($item in $InputObject) {
            if (Test-JsonContainsToken -InputObject $item -Token $Token) {
                return $true
            }
        }
        return $false
    }

    return ([string]$InputObject -eq $Token)
}

function Merge-WorkflowRegistryObject {
    param(
        [object]$TargetJson,
        [object]$SourceJson
    )

    $targetRegistry = ConvertTo-HashtableRecursive -InputObject $TargetJson
    $sourceRegistry = ConvertTo-HashtableRecursive -InputObject $SourceJson

    if ($null -eq $sourceRegistry) {
        throw "GRM workflow registry source is empty or invalid."
    }

    if ($null -eq $targetRegistry) {
        $targetRegistry = [ordered]@{}
    }

    if (-not ($targetRegistry -is [System.Collections.IDictionary])) {
        throw "Unsupported target workflow registry JSON shape."
    }

    if (-not ($sourceRegistry -is [System.Collections.IDictionary])) {
        throw "Unsupported source workflow registry JSON shape."
    }

    # Shape A: registry as object with top-level workflow ids, for example { "speckit": {...}, "grm": {...} }
    if (-not ($sourceRegistry.Contains("workflows"))) {
        foreach ($key in $sourceRegistry.Keys) {
            $targetRegistry[$key] = $sourceRegistry[$key]
        }
        return $targetRegistry
    }

    # Shape B: Spec Kit registry as { "schema_version": "1.0", "workflows": { "speckit": {...}, "grm": {...} } }
    if ($sourceRegistry.Contains("workflows") -and ($sourceRegistry["workflows"] -is [System.Collections.IDictionary])) {
        if (-not ($targetRegistry.Contains("schema_version")) -and $sourceRegistry.Contains("schema_version")) {
            $targetRegistry["schema_version"] = $sourceRegistry["schema_version"]
        }

        if (-not ($targetRegistry.Contains("workflows")) -or $null -eq $targetRegistry["workflows"]) {
            $targetRegistry["workflows"] = [ordered]@{}
        }

        if (-not ($targetRegistry["workflows"] -is [System.Collections.IDictionary])) {
            throw "Unsupported target workflow registry shape: workflows must be an object."
        }

        foreach ($workflowKey in $sourceRegistry["workflows"].Keys) {
            $targetRegistry["workflows"][$workflowKey] = $sourceRegistry["workflows"][$workflowKey]
        }

        return $targetRegistry
    }

    # Shape C: defensive support for { "workflows": [ { "id": "..." } ] } if future versions change format.
    if ($sourceRegistry.Contains("workflows") -and ($sourceRegistry["workflows"] -is [System.Collections.IEnumerable]) -and -not ($sourceRegistry["workflows"] -is [string])) {
        if (-not ($targetRegistry.Contains("workflows")) -or $null -eq $targetRegistry["workflows"]) {
            $targetRegistry["workflows"] = @()
        }

        $targetWorkflows = @($targetRegistry["workflows"])
        $sourceWorkflows = @($sourceRegistry["workflows"])

        foreach ($sourceWorkflow in $sourceWorkflows) {
            $sourceId = $null
            if ($sourceWorkflow -is [System.Collections.IDictionary]) {
                foreach ($candidateKey in @("id", "name", "key")) {
                    if ($sourceWorkflow.Contains($candidateKey)) {
                        $sourceId = [string]$sourceWorkflow[$candidateKey]
                        break
                    }
                }
            }

            if ([string]::IsNullOrWhiteSpace($sourceId)) {
                $targetWorkflows += $sourceWorkflow
                continue
            }

            $updated = $false
            for ($i = 0; $i -lt $targetWorkflows.Count; $i++) {
                $targetWorkflow = $targetWorkflows[$i]
                if ($targetWorkflow -is [System.Collections.IDictionary]) {
                    foreach ($candidateKey in @("id", "name", "key")) {
                        if ($targetWorkflow.Contains($candidateKey) -and ([string]$targetWorkflow[$candidateKey]) -eq $sourceId) {
                            $targetWorkflows[$i] = $sourceWorkflow
                            $updated = $true
                            break
                        }
                    }
                }
                if ($updated) { break }
            }

            if (-not $updated) {
                $targetWorkflows += $sourceWorkflow
            }
        }

        $targetRegistry["workflows"] = $targetWorkflows
        return $targetRegistry
    }

    throw "Unsupported workflow registry JSON shape."
}

function Install-GrmWorkflows {
    param(
        [string]$SourceRepoPath,
        [string]$TargetPath,
        [System.Collections.Generic.List[string]]$Warnings
    )

    $sourceWorkflowsPath = Join-Path $SourceRepoPath "presets/grm-corporate-governance/workflows"
    $targetWorkflowsPath = Join-Path $TargetPath ".specify/workflows"
    $sourceRegistryPath = Join-Path $sourceWorkflowsPath "workflow-registry.json"
    $targetRegistryPath = Join-Path $targetWorkflowsPath "workflow-registry.json"

    if (-not (Test-Path $sourceWorkflowsPath)) {
        throw "GRM workflows source not found: $sourceWorkflowsPath"
    }

    if (-not (Test-Path $sourceRegistryPath)) {
        throw "GRM workflow registry source not found: $sourceRegistryPath"
    }

    if (-not (Test-Path $targetWorkflowsPath)) {
        New-Item -ItemType Directory -Path $targetWorkflowsPath -Force | Out-Null
    }

    Get-ChildItem -Path $sourceWorkflowsPath -Directory | ForEach-Object {
        $destination = Join-Path $targetWorkflowsPath $_.Name
        Copy-Item -Path $_.FullName -Destination $destination -Recurse -Force
    }

    if (-not (Test-Path $targetRegistryPath)) {
        "{}" | Set-Content -Path $targetRegistryPath -Encoding UTF8
    }

    $sourceJson = Get-Content $sourceRegistryPath -Raw | ConvertFrom-Json
    $targetJson = Get-Content $targetRegistryPath -Raw | ConvertFrom-Json

    $mergedRegistry = Merge-WorkflowRegistryObject -TargetJson $targetJson -SourceJson $sourceJson
    $mergedRegistry | ConvertTo-Json -Depth 30 | Set-Content -Path $targetRegistryPath -Encoding UTF8

    $grmWorkflowPath = Join-Path $targetWorkflowsPath "grm/workflow.yml"
    if (-not (Test-Path $grmWorkflowPath)) {
        throw "GRM workflow was not installed correctly: $grmWorkflowPath"
    }

    $mergedRegistryJson = Get-Content $targetRegistryPath -Raw | ConvertFrom-Json

    if (-not (Test-JsonContainsToken -InputObject $mergedRegistryJson -Token "grm")) {
        throw "GRM workflow registry entry was not merged correctly."
    }

    if (-not (Test-JsonContainsToken -InputObject $mergedRegistryJson -Token "speckit")) {
        throw "Native speckit workflow registry entry is missing after merge."
    }

    $detectedWorkflowEntries = @()
    if ($mergedRegistryJson.PSObject.Properties.Name -contains "workflows") {
        $workflowNode = $mergedRegistryJson.workflows
        if ($workflowNode -is [System.Management.Automation.PSCustomObject]) {
            $detectedWorkflowEntries = @($workflowNode.PSObject.Properties.Name)
        }
        elseif ($workflowNode -is [System.Collections.IEnumerable] -and -not ($workflowNode -is [string])) {
            foreach ($workflow in @($workflowNode)) {
                if ($workflow.PSObject.Properties.Name -contains "id") { $detectedWorkflowEntries += [string]$workflow.id }
                elseif ($workflow.PSObject.Properties.Name -contains "name") { $detectedWorkflowEntries += [string]$workflow.name }
                elseif ($workflow.PSObject.Properties.Name -contains "key") { $detectedWorkflowEntries += [string]$workflow.key }
            }
        }
    }
    else {
        $detectedWorkflowEntries = @($mergedRegistryJson.PSObject.Properties.Name)
    }

    Write-Ok "GRM workflows installed and workflow registry merged"
    return $detectedWorkflowEntries
}

function New-InstallationReport {
    param(
        [string]$ReportPath,
        [string]$Status,
        [string]$ErrorMessage,
        [datetime]$StartTime,
        [datetime]$EndTime,
        [string]$RootPath,
        [string]$TargetPath,
        [string]$InstallMode,
        [string]$EffectiveMode,
        [string]$GitVersion,
        [string]$SpecKitVersion,
        [string]$SpecKitInitCommandForReport,
        [string]$InstalledRemote,
        [string]$InstalledBranch,
        [string]$InstalledCommit,
        [string]$SourceRepoPath,
        [bool]$KeepSourceCache,
        [string[]]$AgentFiles,
        [string[]]$PromptFiles,
        [string[]]$WorkflowEntries,
        [bool]$SamplesCopied,
        [bool]$DocsCopied,
        [bool]$ConstitutionCopied,
        [bool]$BacklogCatalogCopied,
        [string[]]$Missing,
        [string[]]$DeployedArtifacts,
        [string[]]$PreservedArtifacts,
        [string[]]$UndeployedArtifacts,
        [bool]$SkillsShapeValidated,
        [string[]]$ValidatedSkillDirs,
        [System.Collections.Generic.List[string]]$Warnings
    )

    $reportDirectory = Split-Path -Path $ReportPath -Parent
    if (-not [string]::IsNullOrWhiteSpace($reportDirectory) -and -not (Test-Path $reportDirectory)) {
        New-Item -ItemType Directory -Path $reportDirectory -Force | Out-Null
    }

    $agentLines = if ($AgentFiles.Count -gt 0) { ($AgentFiles | Sort-Object | ForEach-Object { "- $_" }) -join "`n" } else { "- none detected" }
    $promptLines = if ($PromptFiles.Count -gt 0) { ($PromptFiles | Sort-Object | ForEach-Object { "- $_" }) -join "`n" } else { "- none detected" }

    # P5b (D-P21-01c, D-P21-03a, D-P21-04): la subseccion de skills no
    # sale de una unica fuente. Assert-SkillShape es quien conoce la
    # forma -devuelve, via Install-CorporateSkills sin cambiar su
    # contrato, los directorios que pasaron la validacion-, y el
    # recuento de ficheros por directorio se deriva de DeployedArtifacts,
    # que ya es la fuente de verdad de procedencia (la misma lista que
    # alimenta Assert-DeployedProvenance). _shared aparece aqui porque
    # tambien despliega ficheros con la etiqueta "corp skill file:",
    # pero nunca entra en ValidatedSkillDirs por no tener SKILL.md: se
    # distingue, no se omite, para no contradecir el recuento de
    # Deployed Corporate Artifacts.
    $skillFileGroups = [ordered]@{}
    foreach ($entry in $DeployedArtifacts) {
        $entryParts = $entry -split '\|', 3
        if ($entryParts.Count -lt 1) { continue }
        $entryLabel = $entryParts[0]
        if (-not $entryLabel.StartsWith("corp skill file: ")) { continue }
        $skillRelative = $entryLabel.Substring("corp skill file: ".Length)
        $skillTopDir = ($skillRelative -split '[\\/]')[0]
        if (-not $skillFileGroups.Contains($skillTopDir)) { $skillFileGroups[$skillTopDir] = 0 }
        $skillFileGroups[$skillTopDir] = $skillFileGroups[$skillTopDir] + 1
    }

    if (-not $SkillsShapeValidated) {
        # Estado 3 (D-P21-04): la ejecucion nunca llego a este paso.
        # Distinto de "sin skills": aqui no se sabe si las habria habido.
        $skillLines = "- shape validation not executed: installation stopped before this step"
    }
    elseif ($skillFileGroups.Count -eq 0) {
        # Estado 2 (D-P21-04): la validacion corrio y no encontro ningun
        # directorio de skill, declarado o no, en la Source of Truth.
        $skillLines = "- shape validated: no skill directories found in the Source of Truth"
    }
    else {
        # Estado 1 (D-P21-04): validadas y desplegadas. Una linea por
        # directorio, ordenada por nombre para que el informe sea
        # reproducible byte a byte entre ejecuciones con el mismo payload.
        $skillLines = ($skillFileGroups.Keys | Sort-Object | ForEach-Object {
            $skillDirName = $_
            $skillFileCount = $skillFileGroups[$skillDirName]
            $skillFileWord = if ($skillFileCount -eq 1) { "file" } else { "files" }
            if ($ValidatedSkillDirs -contains $skillDirName) {
                "- ${skillDirName}: $skillFileCount $skillFileWord, shape validated"
            } else {
                "- ${skillDirName}: $skillFileCount $skillFileWord, not a skill (no SKILL.md)"
            }
        }) -join "`n"
    }

    $workflowLines = if ($WorkflowEntries.Count -gt 0) { ($WorkflowEntries | Sort-Object | ForEach-Object { "- $_" }) -join "`n" } else { "- none detected" }
    $missingLines = if ($Missing.Count -gt 0) { ($Missing | ForEach-Object { "- $_" }) -join "`n" } else { "- none" }
    $warningLines = if ($Warnings.Count -gt 0) { ($Warnings | ForEach-Object { "- $_" }) -join "`n" } else { "- none" }
    $deployedLines = if ($DeployedArtifacts.Count -gt 0) { ($DeployedArtifacts | Sort-Object | ForEach-Object { $p = $_ -split '\|', 3; "- $($p[0]): ``$($p[1])`` -> ``$($p[2])``" }) -join "`n" } else { "- none" }
    $preservedLines = if ($PreservedArtifacts.Count -gt 0) { ($PreservedArtifacts | Sort-Object | ForEach-Object { "- $_" }) -join "`n" } else { "- none" }
    $undeployedLines = if ($UndeployedArtifacts.Count -gt 0) { ($UndeployedArtifacts | Sort-Object | ForEach-Object { "- $_" }) -join "`n" } else { "- none" }
    $errorBlock = if ([string]::IsNullOrWhiteSpace($ErrorMessage)) { "- none" } else { "- $ErrorMessage" }

    $content = @"
# GRM Custom Spec Kit Installation Report

## Status

$Status

## Execution

| Field | Value |
|---|---|
| Started | $StartTime |
| Finished | $EndTime |
| Root | $RootPath |
| Target | $TargetPath |
| Requested install mode | $InstallMode |
| Effective install mode | $EffectiveMode |
| Git | $GitVersion |
| Spec Kit (detected) | $SpecKitVersion |
| Spec Kit init command | $SpecKitInitCommandForReport |

## GRM Customization Source

| Field | Value |
|---|---|
| Repository | $InstalledRemote |
| Branch | $InstalledBranch |
| Commit | $InstalledCommit |
| Cache path | $SourceRepoPath |
| Cache retained | $KeepSourceCache |

## Installed Runtime

### Agents

$agentLines

### Prompts

$promptLines

### Skills

$skillLines

### Workflows

$workflowLines

## Deployed Corporate Artifacts

$deployedLines

## Preserved Native Artifacts

Verified intact under Spec Kit (detected): $SpecKitVersion

$preservedLines

## Not Deployed (present in Source of Truth, not declared)

$undeployedLines

## Supporting Assets

| Asset | Copied |
|---|---|
| samples | $SamplesCopied |
| docs | $DocsCopied |
| constitution | $ConstitutionCopied |
| backlog catalogue template | $BacklogCatalogCopied |

## Missing Items

$missingLines

## Warnings

$warningLines

## Error Details

$errorBlock
"@

    Set-Content -Path $ReportPath -Value $content -Encoding UTF8
}

