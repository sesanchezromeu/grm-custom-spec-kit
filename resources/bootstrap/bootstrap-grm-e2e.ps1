        $files.Add((Join-Path $TargetPath ".github/agents/$key.agent.md"))
        $files.Add((Join-Path $TargetPath ".github/prompts/$key.prompt.md"))
    }
    return $files
}

function Get-FileHashSnapshot {
    # Captura hash SHA256 de una lista de ficheros. Los ausentes se
    # registran como $null (no se fallan: un nativo ausente no es un
    # nativo corrompido).
    param([System.Collections.Generic.List[string]]$Files)
    $snapshot = @{}
    foreach ($f in $Files) {
        if (Test-Path $f) {
            $snapshot[$f] = (Get-FileHash -Path $f -Algorithm SHA256).Hash
        } else {
            $snapshot[$f] = $null
        }
    }
    return $snapshot
}

function Assert-NativePreservedIntact {
    # Compara snapshot antes/despues. Falla si un nativo que existia
    # antes fue modificado o eliminado durante el despliegue corporativo.
    # Cumple PC-03. Devuelve la lista de ficheros verificados intactos.
    param(
        [hashtable]$Before,
        [hashtable]$After
    )
    $verified = [System.Collections.Generic.List[string]]::new()
    foreach ($file in $Before.Keys) {
        $hashBefore = $Before[$file]
        $hashAfter  = $After[$file]

        if ($null -eq $hashBefore) {
            # No existia antes: fuera de alcance de proteccion (tolerancia de version)
            continue
        }
        if ($null -eq $hashAfter) {
            throw "Native preserved artifact was deleted during corporate deployment: $file"
        }
        if ($hashBefore -ne $hashAfter) {
            throw "Native preserved artifact was modified during corporate deployment: $file"
        }
        $verified.Add($file) | Out-Null
    }
    return $verified
}

function Assert-DeployedProvenance {
    # Verifica que cada artefacto desplegado (label|origen|destino)
    # tiene en destino el mismo contenido que su origen en el SoT.
    # Acumula divergencias en la lista Missing (patron existente).
    # Cumple CA-02 / PC-04.
    param(
        [System.Collections.Generic.List[string]]$Deployed,
        [ref]$Missing
    )
    foreach ($entry in $Deployed) {
        $parts = $entry -split '\|', 3
        if ($parts.Count -lt 3) { continue }
        $from = $parts[1]
        $to   = $parts[2]

        if (-not (Test-Path $to)) {
            $Missing.Value += "provenance-missing: $to"
            continue
        }
        if (-not (Test-Path $from)) {
            $Missing.Value += "provenance-source-missing: $from"
            continue
        }
        $hashFrom = (Get-FileHash -Path $from -Algorithm SHA256).Hash
        $hashTo   = (Get-FileHash -Path $to -Algorithm SHA256).Hash
        if ($hashFrom -ne $hashTo) {
            $Missing.Value += "provenance-mismatch: $to"
        }
    }
}

function Assert-DeployedSourcePrefix {
    # P5a (OBS-P2a-01, D-P21-07b): comprueba que el origen de cada
    # artefacto desplegado cuelga de la Source of Truth y que todas las
    # entradas usan una sola forma de la ruta.
    #
    # $SourceRepoPath se normaliza tras el clon con el mismo proveedor
    # que Install-CorporateSkills. Esta funcion es la guarda que lo
    # verifica: si alguien vuelve a introducir un origen de otro
    # proveedor, deja de ser una etiqueta silenciosamente mal formada y
    # pasa a ser un fallo duro. Mismo criterio que la guarda de prefijo
    # de L-11: la guarda importa mas que la correccion.
    #
    # Pregunta distinta de la de Assert-DeployedProvenance, que compara
    # contenido. Se separan por el mismo motivo que D-P20-01 separo
    # existencia de forma: aisladas, se ejercitan con datos sinteticos
    # sin instalar nada (ver resources/tools/Test-InstallationReport.ps1).
    #
    # Acumula en Missing, el canal existente: la instalacion aborta en la
    # validacion de runtime y el informe se genera igualmente desde el
    # finally, con la entrada visible.
    param(
        [System.Collections.Generic.List[string]]$Deployed,
        [string]$SourceRepoPath,
        [ref]$Missing
    )

    # El separador final es deliberado: sin el, un directorio hermano
    # como '...\source-otro' pasaria por estar dentro de '...\source'.
    $prefix = $SourceRepoPath.TrimEnd('\') + '\'

    foreach ($entry in $Deployed) {
        $parts = $entry -split '\|', 3
        if ($parts.Count -lt 3) {
            $Missing.Value += "deployed-entry-malformed: $entry"
            continue
        }
        $from = $parts[1]
        if (-not $from.StartsWith($prefix, [System.StringComparison]::OrdinalIgnoreCase)) {
            $Missing.Value += "source-prefix-mismatch: $from"
        }
    }
}

function Get-UndeployedMemoryFiles {
    # Lista ficheros de memory/ presentes en el SoT pero NO declarados
    # en deploys.memory. Informativo (H-INST-07). Devuelve nombres.
    param([string]$SourceRepoPath)

    $memoryDir = Join-Path $SourceRepoPath "presets/grm-corporate-governance/memory"
    if (-not (Test-Path $memoryDir)) { return @() }

    $preYml = Join-Path $SourceRepoPath "presets/grm-corporate-governance/preset.yml"
    # deploys.memory declara pares source/target; extraemos los 'source:'
    $declaredSources = @()
    if (Test-Path $preYml) {
        $inDeploys = $false; $inMemory = $false
        foreach ($raw in (Get-Content $preYml)) {
            $line = $raw -replace '\t','    '
            if ($line -match '^\s*#') { continue }
            $trimmed = $line.Trim()
            if ($trimmed -match '^deploys:') { $inDeploys = $true; continue }
            if ($inDeploys -and $trimmed -match '^memory:') { $inMemory = $true; continue }
            if ($inDeploys -and $line -match '^\S') { $inDeploys = $false; $inMemory = $false }
            if ($inMemory -and $trimmed -match '^-?\s*source:\s*(.+)$') {
                $src = $Matches[1].Trim().Trim('"').Trim("'")
                $declaredSources += (Split-Path -Path $src -Leaf)
            }
        }
    }

    $undeployed = @()
    Get-ChildItem -Path $memoryDir -File | ForEach-Object {
        if ($declaredSources -notcontains $_.Name) {
            $undeployed += "memory/$($_.Name)"
        }
    }
    return $undeployed
}

function Read-YamlScalar {
    # Lee un valor escalar anidado un nivel: TopKey -> NestedKey.
    # Devuelve $null si no existe. Parser minimo (Opcion A, escalares).
    param(
        [string]$Path,
        [string]$TopKey,
        [string]$NestedKey
    )
    if (-not (Test-Path $Path)) { return $null }
    $inTop = $false
    $topIndent = -1
    foreach ($raw in (Get-Content $Path)) {
        $line = $raw -replace '\t', '    '
        if ($line -match '^\s*#') { continue }
        if ([string]::IsNullOrWhiteSpace($line)) { continue }
        $indent = ($line -replace '^(\s*).*$', '$1').Length
        $trimmed = $line.Trim()

        if (-not $inTop) {
            if ($trimmed -match "^${TopKey}:") { $inTop = $true; $topIndent = $indent }
            continue
        }
        if ($indent -le $topIndent) { break }
        if ($trimmed -match "^${NestedKey}:\s*(.+)$") {
            $val = $Matches[1].Trim()
            $val = ($val -replace '\s+#.*$', '').Trim()
            $val = $val.Trim('"').Trim("'")
            return $val
        }
    }
    return $null
}

