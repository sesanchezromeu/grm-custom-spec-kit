        }
        Write-Ok "Spec Kit initialized with integration=$Integration and script=$ScriptType"

        if (-not $SkipGitInit) {
            Write-Step "Initialize Git repository"
            Push-Location $TargetPath
            try {
                if (-not (Test-Path (Join-Path $TargetPath ".git"))) {
                    Invoke-GitChecked -Arguments @("init") -ErrorMessage "Unable to initialize Git repository."
                }
                if ($CreateBranch) {
                    Invoke-GitChecked -Arguments @("checkout", "-B", $BranchName) -ErrorMessage "Unable to create or switch Git branch."
                }
            }
            finally {
                Pop-Location
            }
            Write-Ok "Git repository initialized"
        }
    }
    else {
        Write-Step "Update existing workspace"
        Write-SpecKitVersionAdvisory -SourceRepoPath $SourceRepoPath -DetectedVersion $SpecKitVersion -Warnings $Warnings
        Write-Ok "Existing runtime preserved. Spec Kit init was not executed."
    }

    Write-Step "Apply GRM source-of-truth assets"
    $extensionFrom = Join-Path $SourceRepoPath "extensions/grm-corporate-workflow"
    $extensionTo = Join-Path $TargetPath "extensions/grm-corporate-workflow"
    Copy-DirectoryMerge -From $extensionFrom -To $extensionTo -Label "GRM corporate workflow extension" -Warnings $Warnings | Out-Null

    $presetFrom = Join-Path $SourceRepoPath "presets/grm-corporate-governance"
    $presetTo = Join-Path $TargetPath "presets/grm-corporate-governance"
    Copy-DirectoryMerge -From $presetFrom -To $presetTo -Label "GRM corporate governance preset" -Warnings $Warnings | Out-Null

    Write-Step "Capture native preserved snapshot"
    $NativePreservedFiles = Get-NativePreservedFiles -SourceRepoPath $SourceRepoPath -TargetPath $TargetPath
    $NativeHashBefore = Get-FileHashSnapshot -Files $NativePreservedFiles

    Write-Step "Deploy corporate agents and prompts (manifest-driven)"
    $agentsTo = Join-Path $TargetPath ".github/agents"
    $promptsTo = Join-Path $TargetPath ".github/prompts"
    Install-CorporateAgentsAndPrompts -SourceRepoPath $SourceRepoPath -TargetPath $TargetPath -Deployed $DeployedArtifacts

    Write-Step "Deploy corporate skills (manifest-gated, full subtree)"
    # P5b: Install-CorporateSkills no cambia su contrato (D-P21-01c). Lo
    # que cambia es que ya no se descarta su salida: Assert-SkillShape
    # (linea sin Out-Null en su invocacion) devuelve ahora los
    # directorios que pasaron la validacion, y esa devolucion atraviesa
    # Install-CorporateSkills sin tocar su cuerpo, porque ninguna otra
    # instruccion de la funcion deja nada mas sin suprimir en la
    # pipeline: las demas ya usan Out-Null o asignacion.
    $ValidatedSkillDirs = @(Install-CorporateSkills -SourceRepoPath $SourceRepoPath -TargetPath $TargetPath -Deployed $DeployedArtifacts)
    $SkillsShapeValidated = $true

    Write-Step "Verify native preserved artifacts are intact"
    $NativeHashAfter = Get-FileHashSnapshot -Files $NativePreservedFiles
    $PreservedArtifacts = @(Assert-NativePreservedIntact -Before $NativeHashBefore -After $NativeHashAfter)
    Write-Ok "Native preserved artifacts verified intact: $($PreservedArtifacts.Count) file(s)"

    Write-Step "Install GRM workflows"
    $WorkflowEntries = @(Install-GrmWorkflows -SourceRepoPath $SourceRepoPath -TargetPath $TargetPath -Warnings $Warnings)

    Write-Step "Copy supporting assets"
    $SamplesCopied = Copy-DirectoryMerge -From (Join-Path $SourceRepoPath "samples") -To (Join-Path $TargetPath "samples") -Label "GRM samples" -Warnings $Warnings
    $DocsCopied = Copy-DirectoryMerge -From (Join-Path $SourceRepoPath "docs") -To (Join-Path $TargetPath "docs") -Label "GRM docs" -Warnings $Warnings -ExcludeDirectoryNames @("sessions")

    $constitutionSource = Join-Path $SourceRepoPath "presets/grm-corporate-governance/memory/constitution.md"
    $constitutionTarget = Join-Path $TargetPath ".specify/memory/constitution.md"
    $ConstitutionCopied = Copy-FileIfExists -From $constitutionSource -To $constitutionTarget -Label "GRM corporate constitution" -Warnings $Warnings

    # P4: plantilla de catalogo de backlog. Solo el ejemplo se copia, y
    # se sobrescribe siempre (D-P20-07): es nuestra plantilla, no
    # configuracion del consumidor. grm-backlog.yml (sin sufijo) nunca
    # se toca desde aqui, asi que no hay riesgo de pisar la
    # configuracion real del proyecto consumidor.
    $backlogCatalogSource = Join-Path $SourceRepoPath "extensions/grm-corporate-workflow/config/grm-backlog.example.yml"
    $backlogCatalogTarget = Join-Path $TargetPath ".specify/grm-backlog.example.yml"
    $BacklogCatalogCopied = Copy-FileIfExists -From $backlogCatalogSource -To $backlogCatalogTarget -Label "GRM backlog catalogue template" -Warnings $Warnings

    Write-Step "Validate installed runtime"
    $requiredPaths = @(
        ".github/agents",
        ".github/prompts",
        ".specify",
        ".specify/workflows",
        ".specify/workflows/speckit/workflow.yml",
        ".specify/workflows/grm/workflow.yml",
        ".specify/workflows/workflow-registry.json",
        "extensions/grm-corporate-workflow",
        "presets/grm-corporate-governance"
    )

    foreach ($relativePath in $requiredPaths) {
        $fullPath = Join-Path $TargetPath $relativePath
        if (-not (Test-Path $fullPath)) {
            $Missing += $relativePath
        }
    }

    $registryPath = Join-Path $TargetPath ".specify/workflows/workflow-registry.json"
    if (Test-Path $registryPath) {
        $registry = Get-Content $registryPath -Raw | ConvertFrom-Json
        if (-not (Test-JsonContainsToken -InputObject $registry -Token "speckit")) {
            $Missing += ".specify/workflows/workflow-registry.json:speckit"
        }
        if (-not (Test-JsonContainsToken -InputObject $registry -Token "grm")) {
            $Missing += ".specify/workflows/workflow-registry.json:grm"
        }
    }

    Assert-DeployedProvenance -Deployed $DeployedArtifacts -Missing ([ref]$Missing)
    Assert-DeployedSourcePrefix -Deployed $DeployedArtifacts -SourceRepoPath $SourceRepoPath -Missing ([ref]$Missing)
    $UndeployedArtifacts = @(Get-UndeployedMemoryFiles -SourceRepoPath $SourceRepoPath)

    if (Test-Path $agentsTo) {
        $AgentFiles = @(Get-ChildItem -Path $agentsTo -File | Select-Object -ExpandProperty Name)
    }
    if (Test-Path $promptsTo) {
        $PromptFiles = @(Get-ChildItem -Path $promptsTo -File | Select-Object -ExpandProperty Name)
    }

    if ($Missing.Count -gt 0) {
        throw "Runtime validation failed. Missing items: $($Missing -join ', ')"
    }

    Write-Ok "Runtime validation passed"
    $Status = "SUCCESS"
}
catch {
    $CapturedErrorMessage = $_.Exception.Message
    Write-Host "`n[ERROR] Bootstrap failed: $CapturedErrorMessage" -ForegroundColor Red
    $Status = "FAILED"
}
finally {
    $EndTime = Get-Date

    if ($TargetPath -ne "unknown") {
        if ($ReportPath -eq "unknown") {
            $ReportPath = Join-Path $TargetPath "installation-report.md"
        }

        try {
            New-InstallationReport `
                -ReportPath $ReportPath `
                -Status $Status `
                -ErrorMessage $CapturedErrorMessage `
                -StartTime $StartTime `
                -EndTime $EndTime `
                -RootPath $RootPath `
                -TargetPath $TargetPath `
                -InstallMode $InstallMode `
                -EffectiveMode $EffectiveMode `
                -GitVersion $GitVersion `
                -SpecKitVersion $SpecKitVersion `
                -SpecKitInitCommandForReport $SpecKitInitCommandForReport `
                -InstalledRemote $InstalledRemote `
                -InstalledBranch $InstalledBranch `
                -InstalledCommit $InstalledCommit `
                -SourceRepoPath $SourceRepoPath `
                -KeepSourceCache:$KeepSourceCache `
                -AgentFiles $AgentFiles `
                -PromptFiles $PromptFiles `
                -WorkflowEntries $WorkflowEntries `
                -SamplesCopied:$SamplesCopied `
                -DocsCopied:$DocsCopied `
                -ConstitutionCopied:$ConstitutionCopied `
                -BacklogCatalogCopied:$BacklogCatalogCopied `
                -Missing $Missing `
                -DeployedArtifacts $DeployedArtifacts `
                -PreservedArtifacts $PreservedArtifacts `
                -UndeployedArtifacts $UndeployedArtifacts `
                -SkillsShapeValidated:$SkillsShapeValidated `
                -ValidatedSkillDirs $ValidatedSkillDirs `
                -Warnings $Warnings
            Write-Ok "Installation report generated: $ReportPath"
        }
        catch {
            Write-Warn2 "Could not generate installation report: $($_.Exception.Message)"
        }
    }

    if (-not $KeepSourceCache -and (Test-Path $CacheRoot)) {
        try {
            Remove-Item -Path $CacheRoot -Recurse -Force
        }
        catch {
            Write-Warn2 "Could not remove source cache: $CacheRoot"
        }
    }
}

if ($Status -ne "SUCCESS") {
    exit 1
}

Write-Ok "Bootstrap completed"
exit 0
